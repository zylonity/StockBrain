"""Discovery topic registry.

Topics are stored in PostgreSQL and edited by the user, not hard-coded into
logic. The list below is only the *initial seed*, applied once when the table is
empty; after that the database is authoritative and a redeploy never resurrects
a topic the user disabled or deleted.

Query strings are stored templates, deliberately not generated by an LLM on each
tick: that would make discovery non-reproducible and spend model budget on
something a human should review periodically (spec section 35).

Two kinds of query live here, and the distinction is the point:

``ROUTINE``
    Conventional recent-news and thematic searches -- keyword-shaped, answered
    well by a classical index, and cheap.  Brave answers these.

``SEMANTIC``
    Second-order questions: not "what happened to transformers this week" but
    "which public companies gain from a transformer shortage".  A keyword index
    answers these badly; an embedding index answers them well, at roughly ten
    times the price.  Exa answers these, a handful of times a day.

Duplicating routine queries into the semantic provider would double the bill to
rediscover the same articles, which is why they are separate lists on separate
schedules rather than one list run through both backends.
"""

