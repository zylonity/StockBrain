async def seed_default_topics(session: AsyncSession) -> int:
    """Insert the default topics when none exist.  Returns the number inserted.

    Idempotent and non-destructive: if the user has any topics at all, this does
    nothing. Restoring the defaults after deleting them is a deliberate user
    action, not a side effect of restarting the container.
    """
    existing = (
        await session.execute(sa.select(sa.func.count()).select_from(DiscoveryTopic))
    ).scalar_one()
    if existing:
        return 0

    for seed in DEFAULT_TOPICS:
        _insert_topic(session, seed)
        await session.flush()

    await session.flush()
    log.info("discovery_topics_seeded", count=len(DEFAULT_TOPICS))
    return len(DEFAULT_TOPICS)


async def seed_semantic_topic(session: AsyncSession) -> bool:
    """Add the semantic topic to a database that already has routine ones.

    A deployment upgraded from Phase 9 has eight routine topics and would never
    reach :func:`seed_default_topics` again, so the one genuinely new thing the
    provider split introduces would never appear.  Matched by slug and inserted
    at most once; a user who deletes it keeps it deleted.
    """
    seed = next(s for s in DEFAULT_TOPICS if s.slug == SEMANTIC_TOPIC_SLUG)
    existing = (
        await session.execute(sa.select(DiscoveryTopic.id).where(DiscoveryTopic.slug == seed.slug))
    ).scalar_one_or_none()
    if existing is not None:
        return False
    _insert_topic(session, seed)
    await session.flush()
    log.info("semantic_topic_seeded", slug=seed.slug)
    return True


def _insert_topic(session: AsyncSession, seed: TopicSeed) -> None:
    topic = DiscoveryTopic(
        slug=seed.slug,
        name=seed.name,
        description=seed.description,
        enabled=seed.enabled,
        interval_minutes=seed.interval_minutes,
        result_limit=seed.result_limit,
        freshness_days=seed.freshness_days,
        include_domains=[],
        exclude_domains=[],
    )
    session.add(topic)
    # Attached through the relationship rather than by id, so SQLAlchemy orders
    # the inserts itself and the caller needs only one flush.
    for query in seed.queries:
        session.add(
            DiscoveryQuery(
                topic=topic,
                query=query,
                enabled=True,
                search_kind=seed.kind,
            )
        )
